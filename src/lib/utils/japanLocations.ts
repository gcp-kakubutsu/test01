// 地域名から座標を取得する関数
export function getLocationCoordinates(location: string): { lat: number; lng: number } | null {
  if (!location) return null;
  
  // 完全一致を試みる
  if (japanLocationCoordinates[location]) {
    return japanLocationCoordinates[location];
  }
  
  // 部分一致を試みる（例: "東京都新宿区" → "東京 新宿区"）
  for (const key of Object.keys(japanLocationCoordinates)) {
    if (location.includes(key) || key.includes(location)) {
      return japanLocationCoordinates[key];
    }
  }
  
  return null;
}