/**
 * コミュニティ関連のデータを削除するスクリプト
 * 
 * 使用方法:
 * 1. Firebase Consoleにアクセス
 * 2. Firestore Databaseを開く
 * 3. 以下のコレクションを手動で削除
 */

console.log(`
========================================
コミュニティデータの削除手順
========================================

Firebase Console でデータを削除してください:
https://console.firebase.google.com/project/nukune/firestore/data

削除するコレクション:
1. communities コレクション
   - すべてのドキュメントを選択
   - 削除ボタンをクリック

2. posts コレクション  
   - すべてのドキュメントを選択
   - 削除ボタンをクリック

3. インデックスの削除（重複している場合）
   https://console.firebase.google.com/project/nukune/firestore/indexes
   - 重複している posts インデックスのうち1つを削除

========================================
削除完了後の確認
========================================

1. アプリケーションを再起動
   npm run dev

2. 有料会員でログイン

3. コミュニティページにアクセス
   - 有料会員限定メッセージが表示されることを確認

4. 無料会員でログイン

5. コミュニティページにアクセス
   - 「有料会員限定機能です」と表示されることを確認

========================================
`);

// Note: Firebase Admin SDKを使用した自動削除も可能ですが、
// 安全のため手動削除を推奨します